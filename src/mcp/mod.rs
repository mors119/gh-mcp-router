    #[test]
    fn requests_client_roots_and_uses_the_returned_workspace() {
        let (router, _messages) = router(false);
        let initialize = router
            .handle_message(
                r#"{"jsonrpc":"2.0","id":1,"method":"initialize","params":{"capabilities":{"roots":{"listChanged":true}}}}"#,
            )
            .unwrap();
        assert_eq!(serde_json::from_str::<Value>(&initialize).unwrap()["id"], 1);

        let roots_request = router
            .handle_message(r#"{"jsonrpc":"2.0","method":"notifications/initialized"}"#)
            .unwrap();
        let roots_request_value: Value = serde_json::from_str(&roots_request).unwrap();
        assert_eq!(roots_request_value["method"], "roots/list");
        assert_eq!(roots_request_value["id"], "gh-mcp-router-roots");

        assert!(router
            .handle_message(
                r#"{"jsonrpc":"2.0","id":"gh-mcp-router-roots","result":{"roots":[{"uri":"file:///workspace/project"}]}}"#,
            )
            .is_none());
        assert_eq!(
            router.state.lock().unwrap().root,
            Some(PathBuf::from("/workspace/project"))
        );
    }

    #[test]
    fn initialized_and_cancelled_notifications_are_forwarded_without_responses() {
        let (router, messages) = router(false);
        initialize(&router);
        router
            .in_flight
            .lock()
            .unwrap()
            .insert("999".to_owned(), "personal".to_owned());
        assert!(router
            .handle_message(
                r#"{"jsonrpc":"2.0","method":"notifications/cancelled","params":{"requestId":999}}"#
            )
            .is_none());
        assert!(messages
            .lock()
            .unwrap()
            .iter()
            .any(|(_, message)| message["method"] == "notifications/initialized"));
        assert!(messages.lock().unwrap().iter().any(|(profile, message)| {
            profile == "personal" && message["method"] == "notifications/cancelled"
        }));
        router.shutdown();
    }
