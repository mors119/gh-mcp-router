    #[derive(Clone)]
    struct Launcher {
        messages: Messages,
        mismatch: bool,
    }

    struct Process {
        profile: String,
        messages: Messages,
        mismatch: bool,
    }

    impl UpstreamProcess for Process {
        fn send(&self, message: &str) -> Result<String, UpstreamProcessError> {
            let value: Value =
                serde_json::from_str(message).map_err(|_| UpstreamProcessError::InvalidResponse)?;
            self.messages
                .lock()
                .unwrap()
                .push((self.profile.clone(), value.clone()));
            let id = value.get("id").cloned().unwrap_or(Value::Null);
            let method = value
                .get("method")
                .and_then(Value::as_str)
                .unwrap_or_default();
            let response = match method {
                "initialize" => json!({
                    "jsonrpc":"2.0", "id":id,
                    "result":{"protocolVersion":"2025-06-18","capabilities":{"tools":{"listChanged":false}},"serverInfo":{"name":"fake","version":"1"}}
                }),
                "tools/list" => {
                    let name = if self.mismatch && self.profile == "work" {
                        "different_tool"
                    } else {
                        "get_me"
                    };
                    json!({"jsonrpc":"2.0","id":id,"result":{"tools":[{"name":name,"description":"fake","inputSchema":{"type":"object"}}]}})
                }
                "tools/call" => {
                    let tool = value
                        .get("params")
                        .and_then(|v| v.get("name"))
                        .and_then(Value::as_str)
                        .unwrap_or_default();
                    if tool == "upstream_error" {
                        json!({"jsonrpc":"2.0","id":id,"error":{"code":-32010,"message":"synthetic upstream failure"}})
                    } else {
                        json!({"jsonrpc":"2.0","id":id,"result":{"content":[{"type":"text","text":self.profile}]}})
                    }
                }
                "shutdown" => json!({"jsonrpc":"2.0","id":id,"result":null}),
                _ => json!({"jsonrpc":"2.0","id":id,"result":{}}),
            };
            Ok(response.to_string())
        }

        fn notify(&self, message: &str) -> Result<(), UpstreamProcessError> {
            let value: Value =
                serde_json::from_str(message).map_err(|_| UpstreamProcessError::InvalidResponse)?;
            self.messages
                .lock()
                .unwrap()
                .push((self.profile.clone(), value));
            Ok(())
        }

        fn is_alive(&self) -> bool {
            true
        }

        fn shutdown(&self) {}
    }

    impl UpstreamLauncher for Launcher {
        fn launch(
            &self,
            request: UpstreamLaunchRequest,
        ) -> Result<Box<dyn UpstreamProcess>, UpstreamLaunchError> {
            let token = request
                .environment()
                .get("GITHUB_PERSONAL_ACCESS_TOKEN")
                .unwrap()
                .expose();
            let profile = if token.contains("PERSONAL") {
                "personal"
            } else {
                "work"
            };
            Ok(Box::new(Process {
                profile: profile.to_owned(),
                messages: Arc::clone(&self.messages),
                mismatch: self.mismatch,
            }))
        }
    }

    fn router(mismatch: bool) -> (McpRouter<Credentials, Launcher>, Messages) {
        let mut profiles = std::collections::BTreeMap::new();
        profiles.insert(
            "personal".to_owned(),
            ProfileConfig {
                provider: "gh".to_owned(),
                user: "personal".to_owned(),
                gh_config_dir: None,
                host: None,
            },
        );
        profiles.insert(
            "work".to_owned(),
            ProfileConfig {
                provider: "gh".to_owned(),
                user: "work".to_owned(),
                gh_config_dir: None,
                host: None,
            },
        );
        let mut personal = RouteRule::for_profile("personal");
        personal.owner = Some("PersonalOrg".to_owned());
        let mut work = RouteRule::for_profile("work");
        work.owner = Some("WorkOrg".to_owned());
        let config = Config {
            profiles,
            routes: vec![personal, work],
            default_profile: None,
            ambiguity_policy: Default::default(),
        };
        let messages = Arc::new(Mutex::new(Vec::new()));
        let launcher = Launcher {
            messages: Arc::clone(&messages),
            mismatch,
        };
        let credentials = Credentials(Arc::new(
            [
                ("personal".to_owned(), "ghp_PERSONAL_SYNTHETIC".to_owned()),
                ("work".to_owned(), "github_pat_WORK_SYNTHETIC".to_owned()),
            ]
            .into_iter()
            .collect(),
        ));
        (
            McpRouter::new(config, credentials, launcher, UpstreamConfig::default()),
            messages,
        )
    }

    fn initialize(router: &McpRouter<Credentials, Launcher>) {
        let response = router
            .handle_message(
                r#"{"jsonrpc":"2.0","id":1,"method":"initialize","params":{"protocolVersion":"2025-06-18"}}"#,
            )
            .unwrap();
        assert_eq!(serde_json::from_str::<Value>(&response).unwrap()["id"], 1);
        assert!(router
            .handle_message(r#"{"jsonrpc":"2.0","method":"notifications/initialized"}"#)
            .is_none());
    }

    #[test]
    fn forwards_one_tool_surface_and_routes_a_and_b() {
        let (router, messages) = router(false);
        initialize(&router);
        let tools = router
            .handle_message(r#"{"jsonrpc":"2.0","id":2,"method":"tools/list","params":{}}"#)
            .unwrap();
        assert_eq!(
            serde_json::from_str::<Value>(&tools).unwrap()["result"]["tools"][0]["name"],
            "get_me"
        );
        let personal = router
            .handle_message(r#"{"jsonrpc":"2.0","id":3,"method":"tools/call","params":{"name":"get_me","arguments":{"owner":"PersonalOrg","repo":"repo"}}}"#)
            .unwrap();
        let work = router
            .handle_message(r#"{"jsonrpc":"2.0","id":4,"method":"tools/call","params":{"name":"get_me","arguments":{"owner":"WorkOrg","repo":"repo"}}}"#)
            .unwrap();
        assert_eq!(
            serde_json::from_str::<Value>(&personal).unwrap()["result"]["content"][0]["text"],
            "personal"
        );
        assert_eq!(
            serde_json::from_str::<Value>(&work).unwrap()["result"]["content"][0]["text"],
            "work"
        );
        let calls = messages
            .lock()
            .unwrap()
            .iter()
            .filter(|(_, message)| message["method"] == "tools/call")
            .count();
        assert_eq!(calls, 2);
        for profile in ["personal", "work"] {
            let methods = messages
                .lock()
                .unwrap()
                .iter()
                .filter(|(message_profile, _)| message_profile == profile)
                .filter_map(|(_, message)| message["method"].as_str())
                .map(str::to_owned)
                .collect::<Vec<_>>();
            assert_eq!(
                methods,
                if profile == "personal" {
                    vec![
                        "initialize",
                        "notifications/initialized",
                        "tools/list",
                        "tools/list",
                        "tools/call",
                    ]
                } else {
                    vec![
                        "initialize",
                        "notifications/initialized",
                        "tools/list",
                        "tools/call",
                    ]
                }
                .into_iter()
                .map(str::to_owned)
                .collect::<Vec<_>>()
            );
        }
        assert!(messages.lock().unwrap().iter().any(|(_, message)| {
            message["id"] == 3
                && message["params"]["arguments"]["owner"] == "PersonalOrg"
                && message["params"]["arguments"]["repo"] == "repo"
        }));
    }

    #[test]
    fn concurrent_calls_keep_responses_with_their_profile() {
        let (router, _messages) = router(false);
        initialize(&router);
        let router = Arc::new(router);
        let handles = [("PersonalOrg", "personal"), ("WorkOrg", "work")]
            .into_iter()
            .map(|(owner, expected)| {
                let router = Arc::clone(&router);
                thread::spawn(move || {
                    let message = format!(r#"{{"jsonrpc":"2.0","id":"{expected}","method":"tools/call","params":{{"name":"get_me","arguments":{{"owner":"{owner}","repo":"repo"}}}}}}"#);
                    (expected, router.handle_message(&message).unwrap())
                })
            })
            .collect::<Vec<_>>();
        for handle in handles {
            let (expected, response) = handle.join().unwrap();
            assert_eq!(
                serde_json::from_str::<Value>(&response).unwrap()["result"]["content"][0]["text"],
                expected
            );
        }
    }

    #[test]
    fn non_repository_reads_require_an_explicit_default_and_errors_are_forwarded() {
        let (mut router, _messages) = router(false);
        assert!(router
            .handle_message(r#"{"jsonrpc":"2.0","id":1,"method":"tools/call","params":{"name":"get_me","arguments":{}}}"#)
            .unwrap()
            .contains("not initialized"));
        initialize(&router);
        let response = router
            .handle_message(r#"{"jsonrpc":"2.0","id":2,"method":"tools/call","params":{"name":"upstream_error","arguments":{"owner":"PersonalOrg","repo":"repo"}}}"#)
            .unwrap();
        assert_eq!(
            serde_json::from_str::<Value>(&response).unwrap()["error"]["message"],
            "synthetic upstream failure"
        );

        router.config.default_profile = Some("personal".to_owned());
        let fallback = router
            .handle_message(r#"{"jsonrpc":"2.0","id":3,"method":"tools/call","params":{"name":"get_me","arguments":{}}}"#)
            .unwrap();
        assert_eq!(
            serde_json::from_str::<Value>(&fallback).unwrap()["result"]["content"][0]["text"],
            "personal"
        );
        let write = router
            .handle_message(r#"{"jsonrpc":"2.0","id":4,"method":"tools/call","params":{"name":"create_issue","arguments":{}}}"#)
            .unwrap();
        assert!(write.contains("Repository context is missing"));
    }

